#!/usr/bin/env python3
"""Build the DEEPoS glyph tables from native bitmap fonts or a custom TTF.

Outputs one .c table per size. Advance width and box height are printed so the
hand-written headers can stay in sync (DP_GLYPH_ADV / DP_GLYPH_ROWS).
"""
from __future__ import annotations

import argparse
import pathlib

HERE = pathlib.Path(__file__).resolve().parent.parent
TERMINUS = HERE / "tools/fonts/terminus"

CHARS = (
    "".join(chr(c) for c in range(0x20, 0x7F))
    + "".join(chr(c) for c in range(0x410, 0x450))
    + "Ёё«»—–·…№°×→←↑↓▲▼◆●○■□"
)


def metrics(font: ImageFont.FreeTypeFont) -> tuple[int, int, int]:
    ascent, descent = font.getmetrics()
    advance = int(round(font.getlength("M")))
    return ascent, descent, advance


def rasterise(font: ImageFont.FreeTypeFont, ch: str, threshold: int,
              advance: int, height: int, ascent: int) -> list[int]:
    from PIL import Image, ImageDraw

    img = Image.new("L", (advance, height), 0)
    draw = ImageDraw.Draw(img)
    draw.text((0, ascent), ch, font=font, fill=255, anchor="ls")
    rows: list[int] = []
    for y in range(height):
        bits = 0
        for x in range(advance):
            if img.getpixel((x, y)) >= threshold:
                bits |= 1 << (advance - 1 - x)
        rows.append(bits)
    return rows


def load_ttf(path: str, size: int, threshold: int):
    from PIL import ImageFont

    font = ImageFont.truetype(path, size)
    ascent, descent, advance = metrics(font)
    height = ascent + descent
    glyphs = {ord(ch): rasterise(font, ch, threshold, advance, height, ascent) for ch in CHARS}
    return advance, height, glyphs


def load_bdf(path: pathlib.Path):
    raw = path.read_text(encoding="ascii")
    header, *characters = raw.split("\nSTARTCHAR ")
    dimensions = header.split("\nFONTBOUNDINGBOX ", 1)[1].splitlines()[0]
    advance, height, _, _ = map(int, dimensions.split())
    if advance != 8:
        raise ValueError(f"{path.name}: expected eight pixels per bitmap row")
    glyphs = {}
    for character in characters:
        properties, bitmap = character.split("\nBITMAP\n", 1)
        point = int(properties.split("\nENCODING ", 1)[1].splitlines()[0])
        if chr(point) not in CHARS:
            continue
        rows = [int(row, 16) for row in bitmap.split("\nENDCHAR", 1)[0].splitlines()]
        if properties.split("\nBBX ", 1)[1].splitlines()[0] != dimensions or len(rows) != height:
            raise ValueError(f"{path.name}: invalid cell for U+{point:04X}")
        glyphs[point] = rows
    # The upstream font has no U+25A1. Keep the square available to the UI.
    top = (height - 6) // 2
    glyphs.setdefault(0x25A1, [0] * top + [0x7E, 0x42, 0x42, 0x42, 0x42, 0x7E] + [0] * (height - top - 6))
    return advance, height, glyphs


def emit(path: pathlib.Path, bitmap, source: str,
         name: str, glyph_struct: str, lookup: str, glyphs_macro: str,
         rows_macro: str) -> tuple[int, int]:
    advance, height, glyphs = bitmap
    entries = [(ord(ch), glyphs[ord(ch)]) for ch in sorted(set(CHARS))]

    lines = [
        "/* Generated by tools/gen-font.py - do not edit by hand. */",
        f"/* {source} */",
        f'#include "{path.name.replace(".c", ".h")}"',
        "",
        f"#define {glyphs_macro} {len(entries)}",
        f"#define {rows_macro} {height}",
        "",
        f"static const {glyph_struct} dp_{name}_glyphs[{glyphs_macro}] = {{",
    ]
    for cp, rows in entries:
        body = ", ".join(f"0x{b:04x}" for b in rows)
        lines.append(f"    {{ 0x{cp:04X}, {{ {body} }} }},")
    lines += [
        "};",
        "",
        f"const {glyph_struct} *{lookup}(unsigned int codepoint) {{",
        f"    for (unsigned i = 0; i < {glyphs_macro}; i++) {{",
        f"        if (dp_{name}_glyphs[i].codepoint == codepoint)",
        f"            return &dp_{name}_glyphs[i];",
        "    }",
        "    return 0;",
        "}",
        "",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{path.name:20s} glyphs={len(entries)} adv={advance} box={height} "
          f"bytes={path.stat().st_size}")
    return advance, height


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", help="use a custom monospaced TTF instead of the bundled bitmaps")
    ap.add_argument("--threshold", type=int, default=80)
    args = ap.parse_args()

    source = "Terminus bitmap glyphs, SIL OFL 1.1. See tools/fonts/terminus/OFL.TXT."
    body = load_bdf(TERMINUS / "ter-u16b.bdf")
    small = load_bdf(TERMINUS / "ter-u14n.bdf")
    if args.font:
        source = "Glyphs from a user-supplied font."
        body = load_ttf(args.font, 15, args.threshold)
        small = load_ttf(args.font, 12, args.threshold)
    emit(HERE / "apps/launcher/src/dp_font.c", body, source,
         "font", "struct dp_glyph", "dp_font_lookup", "DP_FONT_GLYPHS",
         "DP_GLYPH_ROWS")
    emit(HERE / "apps/launcher/src/dp_font_small.c", small, source,
         "font_small", "struct dp_glyph_small",
         "dp_font_small_lookup", "DP_FONT_SMALL_GLYPHS", "DP_SMALL_ROWS")


if __name__ == "__main__":
    main()
